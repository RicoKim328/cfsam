"""Command line: ``cfsam import <bundle> [-o mission.yaml]``, ``cfsam validate <mission.yaml>``,
``cfsam generate <mission.yaml> -o <dir>``."""
from __future__ import annotations

import argparse
import sys
from pathlib import Path

from . import cmake, cpp, generate, validate, yamlout
from .importer import MissionImportError, import_mission

HEADER = """Generated by cfsam import; edits are overwritten on the next import.
Variant: SIMULATION={simulation}, EDS off."""


def render(bundle: Path, mission_config: str = "sample", simulation: str = "native") -> tuple[str, list[str]]:
    model, warnings = import_mission(bundle, mission_config, simulation)
    return yamlout.dump(model, HEADER.format(simulation=simulation)), warnings


def _load_and_check(path: Path) -> tuple[dict | None, int]:
    try:
        model = validate.load(path)
    except (validate.MissionLoadError, OSError) as exc:
        print(f"cfsam: error: {exc}", file=sys.stderr)
        return None, 2
    findings = validate.validate(model)
    for finding in findings:
        print(finding)
    return model, 1 if any(f.severity == "error" for f in findings) else 0


def run_validate(path: Path) -> int:
    return _load_and_check(path)[1]


def run_generate(path: Path, out_dir: Path) -> int:
    model, status = _load_and_check(path)
    if status:
        if model is not None:
            print("cfsam: error: not generating; fix the errors above", file=sys.stderr)
        return status
    try:
        generate.write_startup_scripts(model, out_dir)
    except OSError as exc:
        print(f"cfsam: error: {exc}", file=sys.stderr)
        return 2
    return 0


def main(argv: list[str] | None = None) -> int:
    parser = argparse.ArgumentParser(prog="cfsam", description=__doc__)
    sub = parser.add_subparsers(dest="command", required=True)
    imp = sub.add_parser("import", help="read a cFS bundle and write mission.yaml (the bundle is not modified)")
    imp.add_argument("bundle", type=Path, help="cFS bundle root (contains <mission>_defs/)")
    imp.add_argument("-o", "--output", type=Path, help="write here instead of stdout")
    imp.add_argument("--mission-config", default="sample", help="MISSIONCONFIG name (default: sample)")
    imp.add_argument("--simulation", default="native", help="SIMULATION value (default: native)")
    val = sub.add_parser("validate", help="check mission.yaml and report findings (exit 1 on errors)")
    val.add_argument("mission", type=Path, help="mission.yaml written by cfsam import")
    gen = sub.add_parser("generate", help="write <dir>/<cpu>/cfe_es_startup.scr from a valid mission.yaml")
    gen.add_argument("mission", type=Path, help="mission.yaml written by cfsam import")
    gen.add_argument("-o", "--output", type=Path, required=True, help="output directory (not the cFS tree)")
    args = parser.parse_args(argv)

    if args.command == "validate":
        return run_validate(args.mission)
    if args.command == "generate":
        return run_generate(args.mission, args.output)
    try:
        text, warnings = render(args.bundle, args.mission_config, args.simulation)
    except (MissionImportError, cmake.CMakeError, cpp.CppError, OSError) as exc:
        print(f"cfsam: error: {exc}", file=sys.stderr)
        return 2
    for warning in warnings:
        print(f"cfsam: warning: {warning}", file=sys.stderr)
    if args.output:
        args.output.write_text(text, encoding="utf-8")
    else:
        sys.stdout.write(text)
    return 0
