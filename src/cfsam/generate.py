"""Generate cFS config files from a validated mission.yaml.

Output goes to a directory the caller names; the cFS tree is never written.
The layout mirrors <MISSION_DEFS>: mission-wide files at the top, per-CPU
files in <cpu>/.
"""
from __future__ import annotations

from pathlib import Path

# Field order of a startup line, as in <defs>/generate_startup.cmake and
# CFE_ES_ParseFileEntry (cfe/modules/es/fsw/src/cfe_es_startupscript.c:342-390).
_FIELDS = ("type", "file", "entry", "name", "priority", "stack", "load_addr", "exception_action")


def _field(key: str, value) -> str:
    if key == "load_addr" and isinstance(value, int):
        return f"0x{value:X}"
    return str(value)


def startup_script(cpu: dict) -> str:
    """cfe_es_startup.scr text: one ``a, b, ...;`` line per entry.

    ES ends a line at ';' and splits fields at ',', dropping whitespace
    (cfe_es_startupscript.c:199-228), so this matches the cmake-written script
    field for field.
    """
    return "".join(", ".join(_field(k, e[k]) for k in _FIELDS) + ";\n" for e in cpu["startup"])


def topicid_values_header(module: dict, stem: str | None = None) -> str:
    """<stem>_topicid_values.h defining the module's TIDVAL macro from mission.yaml topic IDs.

    ``stem`` is the app name, or ``cfe_<m>`` for a core module (the default
    is the module name). Placed in <MISSION_DEFS>/, it replaces the module's
    config/default_<stem>_topicid_values.h for every CPU
    (cfe/cmake/global_functions.cmake:54-111, 196-214; apps/<app>/mission_build.cmake,
    cfe/modules/<m>/mission_build.cmake). MIDs then follow as base | topic.
    """
    stem = stem or module["name"]
    prefix = f"CFSAM_{stem.upper()}"
    guard = f"{prefix}_TOPICID_VALUES_H"
    lines = [
        "/* Generated by cfsam generate from mission.yaml; edits are overwritten. */",
        f"/* Copy to <MISSION_DEFS>/ to override {module['path']}/config/default_{stem}_topicid_values.h. */",
        f"#ifndef {guard}",
        f"#define {guard}",
        "",
        f"#define {module['tidval']}(x) {prefix}_##x##_TOPICID",
        "",
    ]
    lines += [f"#define {prefix}_{t['name']}_TOPICID 0x{int(t['topic_id']):02X}" for t in module["topics"]]
    lines += ["", "#endif", ""]
    return "\n".join(lines)


def _topic_modules(model: dict):
    """(module, stem) for every app and core module whose topics use a TIDVAL macro."""
    # Core modules' mission-level header is cfe_<m>_topicid_values.h
    # (cfe/modules/es/mission_build.cmake); written as cfe_<m>_* it wins over
    # <m>_* and <MISSIONCONFIG>_<m>_* in <MISSION_DEFS>/
    # (global_functions.cmake:196-204, last match kept at :111).
    pairs = [(m, f"cfe_{m['name']}") for m in model.get("core_modules") or []]
    pairs += [(a, a["name"]) for a in model["apps"]]
    return [(m, stem) for m, stem in pairs if m.get("tidval") and m["topics"]]


def write_topicid_headers(model: dict, out_dir: Path) -> list[Path]:
    """One header per app or core module whose topic IDs go through a TIDVAL macro (``tidval``)."""
    paths = []
    for module, stem in _topic_modules(model):
        path = out_dir / f"{stem}_topicid_values.h"
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(topicid_values_header(module, stem), encoding="utf-8")
        paths.append(path)
    return paths


def write_startup_scripts(model: dict, out_dir: Path) -> list[Path]:
    paths = []
    for cpu in model["cpus"]:
        path = out_dir / cpu["name"] / "cfe_es_startup.scr"
        path.parent.mkdir(parents=True, exist_ok=True)
        path.write_text(startup_script(cpu), encoding="utf-8")
        paths.append(path)
    return paths
